-- Добавляет поле "Ссылка на товар" в таблицу products.
-- Выполните этот скрипт в Supabase -> SQL Editor один раз.
--
-- Как это работает: если у товара заполнено поле link, кнопка «Выбрать»
-- в результате квиза откроет эту ссылку в новой вкладке. Если поле
-- пустое — кнопка, как и раньше, откроет WhatsApp (или Telegram/звонок,
-- в зависимости от настроек SITE в assets/app.js).
--
-- Ссылки редактируются в админ-панели: вкладка «Товары и цены» ->
-- колонка «Ссылка на товар».

alter table products add column if not exists link text;
